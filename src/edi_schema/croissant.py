CROISSANT_CONFORMS_URI = "http://mlcommons.org/croissant/1.1"
CROISSANT_CONTEXT = "http://mlcommons.org/croissant/1.1"

# Map each episode `provenance` value to the W3C PROV-O term, after reading the
# actual PROV-O definitions (https://www.w3.org/TR/prov-o/, 2013, read
# 2026-08-31):
#   * `prov:wasDerivedFrom` — "An entity is derived from an entity", i.e. one
#     entity is a revision of, or was based on, another. A `retrospective`
#     episode (recalled from a prior tapeout, no run artifact) is a record
#     *derived from* a prior design state, so this is the nearest fit for the
#     recollection-without-run case. The "expert recollection agent" aspect is
#     better captured by `prov:wasAttributedTo`, noted in HANDOFF as a
#     spec-drift nuance: the spec's sketch is close but not exact.
#   * `prov:wasGeneratedBy` — "An entity is generated by an activity". A
#     `reproduced` episode is the *output of a run activity* whose tool/PDK
#     versions come from the run-manifest, so this is a correct fit.
#   * `synthetic-fixture` — schema-valid validator food, NOT data. No PROV term
#     applies; it is marked non-evidential (`edi:non_evidential`, a private EDI
#     extension term, not a W3C PROV term), so a consumer can see at a glance
#     that this row is not evidence of anything.
PROV_MAPPING: dict[str, str] = {
    "retrospective": "prov:wasDerivedFrom",
    "reproduced": "prov:wasGeneratedBy",
    "synthetic-fixture": "edi:non_evidential",
}


class ProvenanceMappingError(ValueError):
    """An episode `provenance` value cannot be mapped to a PROV-O term.

    Distinct from every schema-validation error code, so a test can tell a
    wrong-provenance-mapping failure apart from any other.
    """

    code = "E_PROV_UNMAPPED_PROVENANCE"


def provenance_to_prov(provenance: str) -> str:
    """Return the PROV-O term for an episode ``provenance`` value.

    Raises :class:`ProvenanceMappingError` (code ``E_PROV_UNMAPPED_PROVENANCE``)
    for a value that has no mapping — the mutation-test surface.
    """
    try:
        return PROV_MAPPING[provenance]
    except KeyError:
        raise ProvenanceMappingError(f"provenance {provenance!r} has no PROV-O mapping") from None


