@dataclass(frozen=True)
class _Field:
    name: str
    description: str
    data_type: str  # a schema.org DataType, e.g. "Text", "Number", "Integer"
    source: str  # JSON path into the episode document


# The mapping from episode fields to Croissant RecordSet columns. ``source`` is
