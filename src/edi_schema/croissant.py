"""Build a Croissant JSON-LD document from episode files.

Croissant (MLCommons, https://mlcommons.org/working-groups/data/croissant/) is the
ML-dataset metadata standard: schema.org-based JSON-LD, natively indexed by
Hugging Face, Kaggle, OpenML, and Google Dataset Search. An episode corpus that
ships ``croissant.json`` is discoverable by every major dataset search surface
for free.

Vendored spec version implemented here:

    Croissant 1.1  --  https://docs.mlcommons.org/croissant/docs/croissant-spec-1.1.html
    Pinned 2026-08-31 (MLCommons announcement 2026-02-12). The Dataset /
    Distribution / RecordSet / Field / Data layers follow the 1.1 vocabulary,
    and `dct:conformsTo` declares the versioned spec URI
    `http://mlcommons.org/croissant/1.1`. 1.1 adds machine-actionable
    provenance (W3C PROV via `prov:` in the JSON-LD context and `cr:annotation`
    / `equivalentProperty` for external-vocabulary linking), which is exactly
    what the W1.3 PROV-O mapping below is emitted as. If MLCommons publishes a
    newer minor that changes these keys, re-pin and update the structural
    self-tests in tests/test_croissant.py.
"""

